type FlowSpec = {
  channels?: readonly ChannelId[];
  en: readonly FlowNode[];
  tr: readonly FlowNode[];
};

const edge = (to: string, label: string | null = null, detail: string | null = null): FlowEdge => ({
  label,
  detail,
  to,
  href: null,
  kind: "node",
  back: false,
});

const n = (
  id: string,
  kind: FlowNode["kind"],
  headline: string,
  edges: readonly FlowEdge[] = [],
  opts: Partial<FlowNode> = {},
): FlowNode => ({
  id,
  kind,
  headline,
  eventId: kind === "trigger" ? id.replace(/^t\./, "") : null,
  detail: null,
  meta: [],
  edges,
  isEntry: kind === "trigger",
  terminal: kind === "exit",
  ...opts,
});

