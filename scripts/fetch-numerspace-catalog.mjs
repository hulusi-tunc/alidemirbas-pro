// Fetches numerspace.com's own catalogue - every category page in both
// languages, and the calculator cards each one lists (name, one-line
// description, link) - and writes src/lib/numerspace-catalog.ts. Run by
// hand when the site changes:  node scripts/fetch-numerspace-catalog.mjs
// Nothing here is invented: names and descriptions are the site's own,
// URLs come from its sitemap, counts are what it lists.
import { writeFileSync } from "node:fs";

const SITE = "https://www.numerspace.com";
const SKIP = new Set(["blog", "about"]);

const sitemap = await (await fetch(`${SITE}/sitemap.xml`)).text();
const urls = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]);

function decode(s) {
  return s
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&#x27;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/\s+/g, " ")
    .trim();
}

async function scrapeCategory(lang, slug) {
  const href = `/${lang}/${slug}`;
  const html = await (await fetch(`${SITE}${href}`)).text();
  const h1 = decode((html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/) ?? [, ""])[1].replace(/<[^>]+>/g, ""));
  const items = [];
  const anchorRe = new RegExp(`<a[^>]*href="(${href}/[^"#?]+)"[^>]*>([\\s\\S]*?)</a>`, "g");
  const seen = new Set();
  for (const m of html.matchAll(anchorRe)) {
    const itemHref = m[1];
    if (seen.has(itemHref)) continue;
    const inner = m[2];
    const name = (inner.match(/<h2[^>]*>([\s\S]*?)<\/h2>/) ?? [, ""])[1];
    if (!name) continue;
    seen.add(itemHref);
    // the description is the first text block after the heading
    const after = inner.slice(inner.indexOf("</h2>") + 5);
    const desc = (after.match(/<(?:p|span|div)[^>]*>([^<]{12,})<\/(?:p|span|div)>/) ?? [, ""])[1];
    items.push({ slug: itemHref.split("/").pop(), name: decode(name.replace(/<[^>]+>/g, "")), description: decode(desc), href: `${SITE}${itemHref}` });
  }
  return { slug, name: h1, href: `${SITE}${href}`, count: items.length, items };
}

const out = {};
for (const lang of ["en", "tr"]) {
  const slugs = [...new Set(urls.filter((u) => u.startsWith(`${SITE}/${lang}/`)).map((u) => u.slice(`${SITE}/${lang}/`.length).split("/")[0]))].filter((s) => s && !SKIP.has(s));
  const categories = [];
  for (const slug of slugs) {
    const cat = await scrapeCategory(lang, slug);
    if (cat.items.length > 0) categories.push(cat);
    else console.error(`  (${lang}/${slug}: no calculator cards, skipped)`);
  }
  out[lang] = categories;
  console.log(`${lang}: ${categories.length} categories, ${categories.reduce((n, c) => n + c.count, 0)} calculators`);
}

const stamp = new Date().toISOString().slice(0, 10);
const ts = `/* GENERATED by scripts/fetch-numerspace-catalog.mjs on ${stamp} from
   numerspace.com's own sitemap and category pages - do not edit by hand,
   re-run the script. Every name, description and link is the site's own. */

export type NumerspaceCalculator = { slug: string; name: string; description: string; href: string };
export type NumerspaceCategory = { slug: string; name: string; href: string; count: number; items: NumerspaceCalculator[] };

export const NUMERSPACE_CATALOG: Record<"en" | "tr", NumerspaceCategory[]> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync("src/lib/numerspace-catalog.ts", ts);
console.log("wrote src/lib/numerspace-catalog.ts");
